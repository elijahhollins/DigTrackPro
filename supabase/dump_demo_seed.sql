-- ================================================================
-- DigTrack Pro — Generate a rebuild seed for the demo account
-- ================================================================
-- WHAT THIS IS
-- ------------
-- The "Example Excavating Inc." demo account was seeded by running SQL
-- directly against the Supabase project (PR #169), so no seed file was ever
-- committed. This query reads the demo data back out of the database and
-- prints a complete, ready-to-run SQL file that recreates it.
--
-- It is a generator, not the seed itself, for one reason: the demo account is
-- live. Crews get added, inventory moves, invoices get written. A static dump
-- committed today starts drifting immediately, while this query always emits
-- the account as it stands right now.
--
-- HOW TO USE
-- ----------
-- 1. Supabase Dashboard -> SQL Editor -> New query -> paste this -> Run.
-- 2. One row with one column comes back. Copy the whole value.
-- 3. Save it as supabase/seed_demo_example_excavating.sql and commit it.
--
-- The generated file is idempotent (INSERT ... ON CONFLICT (id) DO NOTHING),
-- so running it against an account that still has its data changes nothing.
-- It restores content only; it does not touch companies or profiles, and it
-- writes the dates exactly as they stand when generated. Run
-- refresh_demo_dates.sql afterwards to re-anchor them to the current day.
--
-- SCOPE / LIMITS
-- --------------
--   * Tied to this account: company and profile UUIDs are embedded, so the
--     output restores into THIS project. It is not a portable fixture for a
--     fresh project — there, the company and its logins must exist first.
--   * Does not carry Storage objects. Blueprint PDFs and photos referenced by
--     job_prints.storage_path / inbound_ticket_photos.storage_path live in
--     Storage buckets and are not part of this dump.
--   * profiles / auth users are not dumped. The generated file checks they
--     exist and stops with a clear message if they do not.
-- ================================================================

SELECT
  '-- ================================================================' || E'\n' ||
  '-- DigTrack Pro — Demo account content seed (Example Excavating Inc.)' || E'\n' ||
  '-- ================================================================' || E'\n' ||
  '-- GENERATED by supabase/dump_demo_seed.sql on ' || to_char(now(), 'YYYY-MM-DD HH24:MI') || ' UTC.' || E'\n' ||
  '-- Do not hand-edit: regenerate instead.' || E'\n' ||
  '--' || E'\n' ||
  '-- Restores the demo account''s content into project fusubnzndmngjfgatzrq.' || E'\n' ||
  '-- Safe to re-run: every insert is ON CONFLICT (id) DO NOTHING, so rows that' || E'\n' ||
  '-- still exist are left exactly as they are.' || E'\n' ||
  '--' || E'\n' ||
  '-- Dates below are frozen as of generation time. After seeding, run' || E'\n' ||
  '-- supabase/refresh_demo_dates.sql to slide them to the current day.' || E'\n' ||
  '--' || E'\n' ||
  '-- Requires (and does not create): the company row and the three demo' || E'\n' ||
  '-- profiles, plus their auth users for login.' || E'\n' ||
  '-- ================================================================' || E'\n\n' ||
  'DO $do$' || E'\n' ||
  'DECLARE' || E'\n' ||
  '  v_company  uuid := ' || quote_literal(c.company::text) || ';' || E'\n' ||
  '  v_profiles uuid[] := ARRAY[' ||
      (SELECT string_agg(quote_literal(p.id::text), ', ' ORDER BY p.id)
         FROM profiles p WHERE p.company_id = c.company) || ']::uuid[];' || E'\n' ||
  '  v_order    text[] := ARRAY[' || E'\n' ||
  '    -- parents before children, so the foreign keys hold at every step' || E'\n' ||
  '    ''inventory_locations'', ''cost_codes'', ''materials'', ''employees'',' || E'\n' ||
  '    ''schedule_crews'', ''time_clock_crews'', ''work_log_templates'',' || E'\n' ||
  '    ''job_invoice_templates'', ''invoice_settings'', ''jobs'', ''service_jobs'',' || E'\n' ||
  '    ''tickets'', ''inbound_tickets'', ''job_prints'', ''inventory_items'',' || E'\n' ||
  '    ''inventory_movements'', ''notes'', ''no_shows'', ''ticket_updates'',' || E'\n' ||
  '    ''print_markers'', ''pdf_annotations'', ''photos'', ''inbound_ticket_notes'',' || E'\n' ||
  '    ''inbound_ticket_photos'', ''inbound_ticket_time_entries'', ''schedule_blocks'',' || E'\n' ||
  '    ''time_entries'', ''job_cost_codes'', ''daily_reports'', ''work_logs'',' || E'\n' ||
  '    ''invoices'', ''job_invoices''' || E'\n' ||
  '  ];' || E'\n' ||
  '  -- Tables whose id comes from a sequence: it must end up past the' || E'\n' ||
  '  -- restored ids, or the next app insert collides with seeded data.' || E'\n' ||
  '  v_seqs     text[] := ARRAY[' || E'\n' ||
  '    ''cost_codes'', ''materials'', ''employees'', ''time_clock_crews'',' || E'\n' ||
  '    ''work_log_templates'', ''job_invoice_templates'', ''invoice_settings'',' || E'\n' ||
  '    ''service_jobs'', ''time_entries'', ''job_cost_codes'', ''daily_reports'',' || E'\n' ||
  '    ''work_logs'', ''invoices'', ''job_invoices''' || E'\n' ||
  '  ];' || E'\n' ||
  '  v_data     jsonb;' || E'\n' ||
  '  v_tbl      text;' || E'\n' ||
  '  v_rows     bigint;' || E'\n' ||
  '  v_total    bigint := 0;' || E'\n' ||
  '  v_missing  uuid[];' || E'\n' ||
  'BEGIN' || E'\n' ||
  '  IF NOT EXISTS (SELECT 1 FROM public.companies WHERE id = v_company) THEN' || E'\n' ||
  '    RAISE EXCEPTION ''Company % does not exist. This file restores content into an existing account; create the company and its logins first.'', v_company;' || E'\n' ||
  '  END IF;' || E'\n\n' ||
  '  SELECT array_agg(p) INTO v_missing FROM unnest(v_profiles) p' || E'\n' ||
  '   WHERE NOT EXISTS (SELECT 1 FROM public.profiles x WHERE x.id = p);' || E'\n' ||
  '  IF v_missing IS NOT NULL THEN' || E'\n' ||
  '    RAISE EXCEPTION ''Missing demo profile(s) %. Rows below reference them, so seeding would violate foreign keys. Recreate the logins first.'', v_missing;' || E'\n' ||
  '  END IF;' || E'\n\n' ||
  '  v_data := $json$' || E'\n' || jsonb_pretty(p.payload) || E'\n' || '  $json$::jsonb;' || E'\n\n' ||
  '  FOREACH v_tbl IN ARRAY v_order LOOP' || E'\n' ||
  '    -- A table with no rows is absent from the payload; guard on the type' || E'\n' ||
  '    -- too, since a JSON null would not be SQL NULL here.' || E'\n' ||
  '    CONTINUE WHEN jsonb_typeof(v_data -> v_tbl) IS DISTINCT FROM ''array'';' || E'\n' ||
  '    EXECUTE format(' || E'\n' ||
  '      ''INSERT INTO public.%1$I SELECT * FROM jsonb_populate_recordset(null::public.%1$I, $1) ON CONFLICT (id) DO NOTHING'',' || E'\n' ||
  '      v_tbl) USING v_data -> v_tbl;' || E'\n' ||
  '    GET DIAGNOSTICS v_rows = ROW_COUNT;' || E'\n' ||
  '    v_total := v_total + v_rows;' || E'\n' ||
  '    IF v_rows > 0 THEN' || E'\n' ||
  '      RAISE NOTICE ''  % rows  %'', lpad(v_rows::text, 4), v_tbl;' || E'\n' ||
  '    END IF;' || E'\n' ||
  '  END LOOP;' || E'\n\n' ||
  '  FOREACH v_tbl IN ARRAY v_seqs LOOP' || E'\n' ||
  '    EXECUTE format(' || E'\n' ||
  '      ''SELECT setval(pg_get_serial_sequence(''''public.%1$I'''', ''''id''''), greatest(coalesce((SELECT max(id) FROM public.%1$I), 0), 1))'',' || E'\n' ||
  '      v_tbl);' || E'\n' ||
  '  END LOOP;' || E'\n\n' ||
  '  RAISE NOTICE ''Seeded % row(s). Now run refresh_demo_dates.sql to anchor the dates to today.'', v_total;' || E'\n' ||
  'END $do$;' || E'\n'
  AS seed_file
FROM (SELECT 'da0eea4d-b2c2-4b7f-b31a-5c5dd87f272d'::uuid AS company) c
CROSS JOIN LATERAL (
  -- Keys are dropped for tables with no rows. Note this filters the top level
  -- only: jsonb_strip_nulls would recurse and quietly rewrite nulls stored
  -- inside invoice / work-log / audit payloads.
  SELECT (SELECT jsonb_object_agg(k, v) FROM jsonb_each(jsonb_build_object(
    'inventory_locations',         (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM inventory_locations x WHERE x.company_id = c.company),
    'cost_codes',                  (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM cost_codes x WHERE x.company_id = c.company),
    'materials',                   (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM materials x WHERE x.company_id = c.company),
    'employees',                   (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM employees x WHERE x.company_id = c.company),
    'schedule_crews',              (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM schedule_crews x WHERE x.company_id = c.company),
    'time_clock_crews',            (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM time_clock_crews x WHERE x.company_id = c.company),
    'work_log_templates',          (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM work_log_templates x WHERE x.company_id = c.company),
    'job_invoice_templates',       (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM job_invoice_templates x WHERE x.company_id = c.company),
    'invoice_settings',            (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM invoice_settings x WHERE x.company_id = c.company),
    'jobs',                        (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM jobs x WHERE x.company_id = c.company),
    'service_jobs',                (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM service_jobs x WHERE x.company_id = c.company),
    'tickets',                     (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM tickets x WHERE x.company_id = c.company),
    'inbound_tickets',             (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM inbound_tickets x WHERE x.company_id = c.company),
    'job_prints',                  (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM job_prints x WHERE x.company_id = c.company),
    'inventory_items',             (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM inventory_items x WHERE x.company_id = c.company),
    'inventory_movements',         (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM inventory_movements x WHERE x.company_id = c.company),
    'notes',                       (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM notes x WHERE x.company_id = c.company),
    'no_shows',                    (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM no_shows x WHERE x.company_id = c.company),
    'ticket_updates',              (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM ticket_updates x WHERE x.company_id = c.company),
    'print_markers',               (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM print_markers x WHERE x.ticket_id IN (SELECT t.id FROM tickets t WHERE t.company_id = c.company)),
    'pdf_annotations',             (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM pdf_annotations x WHERE x.company_id = c.company),
    'photos',                      (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM photos x WHERE x.company_id = c.company),
    'inbound_ticket_notes',        (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM inbound_ticket_notes x WHERE x.ticket_id IN (SELECT i.id FROM inbound_tickets i WHERE i.company_id = c.company)),
    'inbound_ticket_photos',       (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM inbound_ticket_photos x WHERE x.ticket_id IN (SELECT i.id FROM inbound_tickets i WHERE i.company_id = c.company)),
    'inbound_ticket_time_entries', (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM inbound_ticket_time_entries x WHERE x.company_id = c.company),
    'schedule_blocks',             (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM schedule_blocks x WHERE x.company_id = c.company),
    'time_entries',                (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM time_entries x WHERE x.company_id = c.company),
    'job_cost_codes',              (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM job_cost_codes x WHERE x.company_id = c.company),
    'daily_reports',               (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM daily_reports x WHERE x.company_id = c.company),
    'work_logs',                   (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM work_logs x WHERE x.job_id IN (SELECT s.id FROM service_jobs s WHERE s.company_id = c.company)),
    'invoices',                    (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM invoices x WHERE x.company_id = c.company),
    'job_invoices',                (SELECT jsonb_agg(to_jsonb(x) ORDER BY x.id) FROM job_invoices x WHERE x.company_id = c.company)
  )) AS e(k, v) WHERE jsonb_typeof(v) = 'array') AS payload
) p;
